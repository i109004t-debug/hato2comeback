export const CAMPAIGN_TRANSITIONS = Object.freeze({
  DRAFT: ['PENDING_APPROVAL', 'APPROVED'],
  PENDING_APPROVAL: ['APPROVED', 'DRAFT'],
  APPROVED: ['QUEUED', 'SCHEDULED', 'NEEDS_REVIEW', 'CANCELLED'],
  SCHEDULED: ['APPROVED', 'QUEUED', 'NEEDS_REVIEW', 'CANCELLED'],
  QUEUED: ['APPROVED', 'PENDING_APPROVAL', 'SENDING', 'PAUSED', 'NEEDS_REVIEW', 'CANCELLED'],
  SENDING: ['PAUSED', 'COMPLETED', 'NEEDS_REVIEW', 'CANCELLED'],
  PAUSED: ['QUEUED', 'SENDING', 'NEEDS_REVIEW', 'CANCELLED'],
  NEEDS_REVIEW: ['QUEUED', 'CANCELLED'],
  COMPLETED: [], CANCELLED: [],
});

export const canTransition = (from, to) => Object.hasOwn(CAMPAIGN_TRANSITIONS, from) && (from === to || CAMPAIGN_TRANSITIONS[from].includes(to));
